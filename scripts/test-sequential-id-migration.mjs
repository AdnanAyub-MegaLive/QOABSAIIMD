import { config } from "dotenv";
import pg from "pg";
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
config({ path: ".env.local", quiet: true });
const db = new pg.Client({ connectionString: process.env.DATABASE_URL });
await db.connect();
try {
  await db.query("BEGIN");
  const schema = `id_test_${Date.now()}`;
  await db.query(`CREATE SCHEMA "${schema}"`);
  await db.query(`SET LOCAL search_path TO "${schema}"`);
  await db.query(`CREATE TYPE "WalletTransactionType" AS ENUM ('BONUS');
    CREATE TABLE "User" (id TEXT PRIMARY KEY, "publicId" TEXT);
    CREATE TABLE "Talent" (id TEXT PRIMARY KEY, "publicId" TEXT);
    CREATE TABLE "Agency" ("publicId" TEXT);
    CREATE TABLE "SpecialIdDefinition" (id TEXT PRIMARY KEY, code TEXT UNIQUE, "defaultDurationMinutes" INT, "updatedAt" TIMESTAMP);
    CREATE TABLE "SpecialIdAssignment" (id TEXT PRIMARY KEY,"specialId" TEXT,status TEXT,"revokedAt" TIMESTAMP,"expiresAt" TIMESTAMP);`);
  await db.query(await readFile("prisma/migrations/20261020100000_sequential_special_ids/migration.sql", "utf8"));
  const allocate = async prefix => (await db.query("SELECT allocate_public_number($1) n", [prefix])).rows[0].n;
  assert.equal(await allocate("USR"), "2030140");
  assert.equal(await allocate("AGN"), "10200");
  assert.equal(await allocate("TLN"), "2030141");
  await db.query("SELECT setval('user_public_number',2030221,false)");
  assert.equal(await allocate("USR"), "2030221");
  assert.equal(await allocate("USR"), "2030223");
  assert.equal((await db.query(`SELECT "storeVisible" FROM "SpecialIdDefinition" WHERE code='2030222'`)).rows[0].storeVisible, false);
  await db.query(`INSERT INTO "SpecialIdDefinition"(id,code) VALUES('manual','2030224')`);
  assert.equal(await allocate("USR"), "2030225");
  await db.query(`DELETE FROM "SpecialIdDefinition" WHERE code='2030224'`);
  assert.equal((await db.query(`SELECT kind FROM "PublicNumberReservation" WHERE number='2030224'`)).rows[0].kind, "SPECIAL");
  await db.query("SELECT setval('user_public_number',2030804,false)");
  assert.equal(await allocate("USR"), "2030805");
  await db.query("SELECT setval('agency_public_number',10804,false)");
  assert.equal(await allocate("AGN"), "10804");
  await db.query("SAVEPOINT collision");
  await assert.rejects(db.query(`INSERT INTO "SpecialIdDefinition"(id,code) VALUES('collision','2030140')`), /SPECIAL_ID_CONFLICTS/);
  await db.query("ROLLBACK TO SAVEPOINT collision");
  console.log("Separate sequences, repeated digits, 804, permanent reservations and collision guards verified. Test schema rolled back.");
} finally { await db.query("ROLLBACK"); await db.end(); }
